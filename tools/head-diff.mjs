#!/usr/bin/env node
// ============================================================================
// tools/head-diff.mjs — head-item parity between a legacy page and its port.
//
// Usage:
//   node tools/head-diff.mjs <legacyUrl> <newUrl> [name]
//
// Fetches both URLs and compares the head items the port owns:
//   - <title>
//   - <meta name="description">, <meta name="robots">
//   - <link rel="canonical">
//   - every Open Graph <meta property="og:*">
//   - <meta name="twitter:card">
//   - every <script type="application/ld+json"> block (JSON.parse + deep equal)
//
// The ONLY allowed difference is the canonical / og:url rewritten from the
// legacy `.html` URL to the clean URL; each such rewrite is listed explicitly.
//
// Fields owned by the SHARED layout (web/app/layout.tsx) or generated by Next
// from `openGraph` (viewport, color-scheme, theme-color, and twitter:title /
// twitter:description when legacy omits them) are reported separately as
// "shared layout (informational)" — they are identical on every ported page
// and a per-page port cannot change them without editing the shared layout.
//
// No dependencies — Node built-ins only (fetch is global on Node >= 18).
// ============================================================================

const [legacyUrl, newUrl, name = "page"] = process.argv.slice(2);
if (!legacyUrl || !newUrl) {
  console.error("Usage: node tools/head-diff.mjs <legacyUrl> <newUrl> [name]");
  process.exit(1);
}

function decodeEntities(s) {
  return s
    .replace(/&quot;/g, '"')
    .replace(/&#x27;/g, "'")
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}

function attr(tag, name) {
  const m = tag.match(new RegExp(name + `\\s*=\\s*"([^"]*)"`, "i"));
  return m ? decodeEntities(m[1]) : null;
}

async function headOf(url) {
  const res = await fetch(url);
  const html = await res.text();
  const m = html.match(/<head[^>]*>([\s\S]*?)<\/head>/i);
  const head = m ? m[1] : html;

  const out = { title: null, metaName: {}, metaProp: {}, canonical: null, ld: [] };
  const title = head.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  if (title) out.title = decodeEntities(title[1]).trim();

  for (const tag of head.match(/<meta\b[^>]*>/gi) || []) {
    const n = attr(tag, "name");
    const p = attr(tag, "property");
    const c = attr(tag, "content");
    if (n && n.toLowerCase() !== "charset") out.metaName[n] = c;
    if (p) out.metaProp[p] = c;
  }

  for (const tag of head.match(/<link\b[^>]*>/gi) || []) {
    if ((attr(tag, "rel") || "").toLowerCase() === "canonical") out.canonical = attr(tag, "href");
  }

  const ldRe = /<script[^>]*type\s*=\s*"application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/gi;
  let ld;
  while ((ld = ldRe.exec(html))) {
    const raw = ld[1].trim();
    try {
      out.ld.push(JSON.parse(raw));
    } catch (e) {
      out.ld.push({ __unparsed: raw });
    }
  }
  return out;
}

const deepEqual = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/* The canonical / og:url rewrite is the only allowed change: the legacy
   `.html` URL is replaced by the clean URL. Return the clean form of a
   legacy URL, or null when the value is not a legacy `.html` URL. */
function cleanForm(url) {
  if (typeof url !== "string") return null;
  if (!/^https?:\/\/[^/]+\/.*\.html$/.test(url)) return null;
  return url.replace(/\.html$/, "");
}

const legacy = await headOf(legacyUrl);
const fresh = await headOf(newUrl);

console.log(`== head-diff ${name} ==`);
console.log(`   legacy: ${legacyUrl}`);
console.log(`   new   : ${newUrl}`);

let fails = 0;
const rewrites = [];
const shared = [];
const ok = (cond, label) => {
  if (!cond) fails++;
  console.log(`  ${cond ? "PASS" : "FAIL"}  ${label}`);
};

/* name metas the port owns. */
const REQUIRED_NAME = new Set(["description", "robots", "twitter:card"]);
/* name metas owned by the shared layout (web/app/layout.tsx) — identical on
   every ported page, so a per-page port cannot change them. */
const SHARED_NAME = new Set(["viewport", "color-scheme", "theme-color"]);

ok(legacy.title === fresh.title, `title: "${legacy.title}"`);
if (legacy.title !== fresh.title) console.log(`        new: "${fresh.title}"`);

{
  const wantClean = cleanForm(legacy.canonical);
  if (fresh.canonical === legacy.canonical) {
    ok(true, `canonical: ${legacy.canonical}`);
  } else if (wantClean && fresh.canonical === wantClean) {
    rewrites.push(`canonical ${legacy.canonical} -> ${fresh.canonical}`);
    console.log(`  PASS  canonical rewritten to clean URL: ${legacy.canonical} -> ${fresh.canonical}`);
  } else {
    ok(false, `canonical: legacy "${legacy.canonical}" vs new "${fresh.canonical}"`);
  }
}

function cmpMap(kind, legacyMap, freshMap, required) {
  const keys = new Set([...Object.keys(legacyMap), ...Object.keys(freshMap)]);
  for (const k of [...keys].sort()) {
    const a = legacyMap[k];
    const b = freshMap[k];
    const isReq = required(k);
    if (a === b) {
      ok(true, `${kind} ${k}: ${JSON.stringify(a)}`);
      continue;
    }
    const wantClean = cleanForm(a);
    if (kind === "property" && k === "og:url" && wantClean && b === wantClean) {
      rewrites.push(`og:url ${a} -> ${b}`);
      console.log(`  PASS  og:url rewritten to clean URL: ${a} -> ${b}`);
      continue;
    }
    if (a === undefined || b === undefined) {
      if (isReq) {
        ok(false, `${kind} ${k}: legacy ${JSON.stringify(a)} vs new ${JSON.stringify(b)}`);
      } else {
        shared.push(`${kind} ${k}: ${a === undefined ? `new adds ${JSON.stringify(b)}` : `legacy-only ${JSON.stringify(a)}`}`);
      }
      continue;
    }
    if (kind === "name" && SHARED_NAME.has(k)) {
      shared.push(`${kind} ${k}: legacy ${JSON.stringify(a)} vs new ${JSON.stringify(b)}`);
      continue;
    }
    ok(false, `${kind} ${k}: legacy ${JSON.stringify(a)} vs new ${JSON.stringify(b)}`);
  }
}
cmpMap("name", legacy.metaName, fresh.metaName, (k) => REQUIRED_NAME.has(k));
cmpMap("property", legacy.metaProp, fresh.metaProp, (k) => k.startsWith("og:"));

{
  const a = legacy.ld;
  const b = fresh.ld;
  ok(a.length === b.length, `ld+json block count: ${a.length}`);
  if (a.length !== b.length) console.log(`        new: ${b.length}`);
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i++) {
    const eq = deepEqual(a[i], b[i]);
    ok(eq, `ld+json[${i}] deep-equal`);
    if (!eq) {
      console.log(`        legacy: ${JSON.stringify(a[i]).slice(0, 400)}`);
      console.log(`        new   : ${JSON.stringify(b[i]).slice(0, 400)}`);
    }
  }
}

if (rewrites.length) {
  console.log("   allowed rewrites (canonical/og:url -> clean URL):");
  for (const r of rewrites) console.log(`     · ${r}`);
}
if (shared.length) {
  console.log("   shared layout (informational, identical on every ported page):");
  for (const s of shared) console.log(`     · ${s}`);
}

console.log(`== ${name}: ${fails === 0 ? "PASS" : `FAIL (${fails} field(s))`} ==`);
process.exit(fails ? 1 : 0);
