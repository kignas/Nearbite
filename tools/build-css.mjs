/* Combines each page's own stylesheets into ONE file so the browser makes one
   render-blocking CSS request instead of ~27. Sources + order come from
   tools/css-bundles.json. Run after editing any listed stylesheet:
     node tools/build-css.mjs          rebuild bundles + the ?v= in the page link
     node tools/build-css.mjs --check  exit 1 if a bundle is stale (used by tests) */
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'tools/css-bundles.json'), 'utf8'));

export function buildBundle(def) {
  const outDir = path.dirname(path.join(root, def.out));
  const parts = def.sources.map(src => {
    let css = fs.readFileSync(path.join(root, src), 'utf8').replace(/^\uFEFF/, '');
    if (/@import\b/.test(css)) throw new Error(src + ': @import is not supported in bundles');
    css = css.replace(/^\s*@charset[^;]*;/i, '');
    /* url() paths are relative to the source file; re-point them at the bundle. */
    css = css.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (all, q, u) => {
      if (/^(data:|https?:|\/|#)/i.test(u)) return all;
      const abs = path.resolve(path.dirname(path.join(root, src)), u);
      return 'url(' + q + path.relative(outDir, abs).split(path.sep).join('/') + q + ')';
    });
    return '/* ==== ' + src + ' ==== */\n' + css.trim() + '\n';
  });
  const body = '/* GENERATED by tools/build-css.mjs - edit the source files, then rebuild. */\n' + parts.join('\n');
  const hash = crypto.createHash('sha1').update(body).digest('hex').slice(0, 10);
  return { body, hash };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check'); let stale = 0;
  for (const [name, def] of Object.entries(manifest)) {
    const { body, hash } = buildBundle(def);
    const outPath = path.join(root, def.out);
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
    if (current !== body) { stale++; if (!check) fs.writeFileSync(outPath, body); }
    for (const page of def.pages) {
      const p = path.join(root, page); let html = fs.readFileSync(p, 'utf8');
      const re = new RegExp('(href="' + def.out.replace(/[.*+?^${}()|[\]\\\/]/g, '\\$&') + ')(\\?v=[^"]*)?"');
      const next = html.replace(re, '$1?v=' + hash + '"');
      if (next !== html) { stale++; if (!check) fs.writeFileSync(p, next); }
    }
    console.log((check ? 'checked ' : 'built ') + name + ' ' + def.out + ' v=' + hash);
  }
  if (check && stale) { console.log('STALE: run node tools/build-css.mjs'); process.exit(1); }
}
